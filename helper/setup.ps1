<#
  Ultimate Turbo Downloader helper setup.
  - finds aria2c.exe (or installs it with winget when you pass -InstallAria2)
  - creates a random RPC secret, aria2.conf and an empty session file
  - finds yt-dlp, ffmpeg and Node for the video helper (or installs yt-dlp with -InstallYtDlp)
  - writes start-helpers.vbs, which runs aria2 + the video helper hidden in the background
  - with -Autostart, puts a shortcut in your Startup folder so both run at every login
  - (re)starts both now

  Usage:  powershell -ExecutionPolicy Bypass -File setup.ps1 [-InstallAria2] [-InstallYtDlp] [-Autostart] [-Dir D:\Downloads]
#>
param(
  [switch]$InstallAria2,
  [switch]$InstallYtDlp,
  [switch]$Autostart,
  [string]$Dir = (Join-Path $env:USERPROFILE 'Downloads'),
  [int]$Port = 6800
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot

function Find-Aria2 {
  $cmd = Get-Command aria2c -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  $cands = @(
    (Join-Path $here 'bin\aria2c.exe'),
    (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links\aria2c.exe')
  )
  $pkg = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages'
  if (Test-Path $pkg) {
    $cands += Get-ChildItem $pkg -Recurse -Filter aria2c.exe -ErrorAction SilentlyContinue | ForEach-Object FullName
  }
  foreach ($c in $cands) { if ($c -and (Test-Path $c)) { return (Resolve-Path $c).Path } }
  return $null
}

$aria2 = Find-Aria2
if (-not $aria2 -and $InstallAria2) {
  Write-Host 'Installing aria2 with winget (package aria2.aria2)...'
  winget install --id aria2.aria2 -e --source winget --accept-package-agreements --accept-source-agreements
  $aria2 = Find-Aria2
}
if (-not $aria2) {
  throw 'aria2c.exe not found. Run again with -InstallAria2, or put aria2c.exe in helper\bin\.'
}
# WinGet "Links" entries are symlinks; the VBS launcher needs the real exe.
$item = Get-Item $aria2
if ($item.LinkType -and $item.Target) { $aria2 = @($item.Target)[0] }
Write-Host "aria2: $aria2"

# --- secret ---
$secretFile = Join-Path $here 'secret.txt'
if (-not (Test-Path $secretFile)) {
  $bytes = New-Object byte[] 24
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  $secret = ([BitConverter]::ToString($bytes) -replace '-', '').ToLower()
  Set-Content -Path $secretFile -Value $secret -NoNewline -Encoding ascii
}
$secret = (Get-Content $secretFile -Raw).Trim()

# --- config + session ---
New-Item -ItemType Directory -Force $Dir | Out-Null
# Unfinished downloads (and their .aria2 / .part pieces) live in a hidden folder inside the
# destination; the video helper moves each file out when it is complete.
$temp = Join-Path $Dir '.utd-temp'
New-Item -ItemType Directory -Force $temp | Out-Null
(Get-Item $temp -Force).Attributes = 'Directory,Hidden'
$session = Join-Path $here 'aria2.session'
if (-not (Test-Path $session)) { New-Item -ItemType File $session | Out-Null }
$conf = Join-Path $here 'aria2.conf'
@"
# Generated by setup.ps1
# Downloads go to a hidden temp folder first; finished files are moved to $Dir
dir=$temp
continue=true
max-concurrent-downloads=5
optimize-concurrent-downloads=true
split=16
max-connection-per-server=16
min-split-size=1M
piece-length=1M
# Large TCP receive buffers: measured 2-3x faster on long-distance (high-latency) servers
socket-recv-buffer-size=16M
uri-selector=adaptive
enable-http-keep-alive=true
file-allocation=none
disk-cache=64M
max-tries=5
retry-wait=3
connect-timeout=30
timeout=60
auto-file-renaming=true
content-disposition-default-utf8=true
check-certificate=true

# RPC: only this computer can reach it, and every call needs the secret
enable-rpc=true
rpc-listen-all=false
rpc-listen-port=$Port
rpc-secret=$secret
rpc-max-request-size=10M

# Resume unfinished downloads after a restart
input-file=$session
save-session=$session
save-session-interval=30
force-save=false

# Keep the finished list for the popup
max-download-result=200
console-log-level=warn
"@ | Set-Content -Path $conf -Encoding ascii

# --- media helper (yt-dlp) config ---
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { Write-Warning 'Node.js not found: the video helper needs it (https://nodejs.org).' }
$ytdlp = (Get-Command yt-dlp -ErrorAction SilentlyContinue).Source
$updateCmd = $null
if (-not $ytdlp -and $InstallYtDlp) {
  Write-Host 'Installing yt-dlp with winget (package yt-dlp.yt-dlp)...'
  winget install --id yt-dlp.yt-dlp -e --source winget --accept-package-agreements --accept-source-agreements
  $ytdlp = (Get-ChildItem (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages') -Recurse -Filter yt-dlp.exe -ErrorAction SilentlyContinue | Select-Object -First 1).FullName
}
if ($ytdlp) {
  $py = Join-Path (Split-Path (Split-Path $ytdlp)) 'python.exe'   # pip install puts yt-dlp.exe in <python>\Scripts
  $updateCmd = if (Test-Path $py) { @($py, '-m', 'pip', 'install', '-U', 'yt-dlp[default]') } else { @($ytdlp, '-U') }
} else { Write-Warning 'yt-dlp not found: run again with -InstallYtDlp to enable video downloads.' }
$ffmpeg = (Get-Command ffmpeg -ErrorAction SilentlyContinue).Source
if (-not $ffmpeg) { Write-Warning 'ffmpeg not found: best-quality YouTube (separate video + audio) and MP3 need it (winget install Gyan.FFmpeg).' }
[ordered]@{
  port = 6801; maxRunning = 3
  ytdlp = $(if ($ytdlp) { $ytdlp } else { 'yt-dlp' })
  ffmpeg = $(if ($ffmpeg) { Split-Path $ffmpeg } else { $null })
  node = $node; aria2c = $aria2; updateCmd = $updateCmd
} | ConvertTo-Json | Set-Content -Path (Join-Path $here 'media.json') -Encoding utf8

# --- hidden launcher for both helpers ---
Remove-Item (Join-Path $here 'start-aria2.vbs') -ErrorAction SilentlyContinue
$vbs = Join-Path $here 'start-helpers.vbs'
$server = Join-Path $here 'media-server.mjs'
@"
' Starts aria2 (files) and the media helper (yt-dlp videos) in the background with no window.
' Generated by setup.ps1
' Each one is only started if it isn't already running.
Set sh = CreateObject("WScript.Shell")
Set wmi = GetObject("winmgmts:\\.\root\cimv2")
If wmi.ExecQuery("SELECT ProcessId FROM Win32_Process WHERE Name='aria2c.exe'").Count = 0 Then
  sh.Run """$aria2"" --conf-path=""$conf""", 0, False
End If
If wmi.ExecQuery("SELECT ProcessId FROM Win32_Process WHERE Name='node.exe' AND CommandLine LIKE '%media-server.mjs%'").Count = 0 Then
  sh.Run """$node"" ""$server""", 0, False
End If
"@ | Set-Content -Path $vbs -Encoding ascii

# --- autostart ---
$startup = [Environment]::GetFolderPath('Startup')
$lnk = Join-Path $startup 'Ultimate Turbo Downloader.lnk'
Remove-Item (Join-Path $startup 'Turbo Downloader (aria2).lnk') -ErrorAction SilentlyContinue   # name used before v1.4
if ($Autostart) {
  $ws = New-Object -ComObject WScript.Shell
  $sc = $ws.CreateShortcut($lnk)
  $sc.TargetPath = Join-Path $env:WINDIR 'System32\wscript.exe'
  $sc.Arguments = "`"$vbs`""
  $sc.WorkingDirectory = $here
  $sc.Save()
  Write-Host "Autostart on: $lnk"
}

# --- start now (restart any running copies so they pick up the new config) ---
& (Join-Path $here 'stop-helpers.ps1') -Quiet
Start-Process -FilePath (Join-Path $env:WINDIR 'System32\wscript.exe') -ArgumentList "`"$vbs`""
Start-Sleep -Seconds 2
try {
  $st = Invoke-RestMethod -Uri 'http://127.0.0.1:6801/status' -Headers @{ 'X-Turbo-Secret' = $secret }
  Write-Host "Video helper is running (yt-dlp $($st.ytdlp)) on port 6801."
} catch {
  Write-Warning "Video helper did not answer on port 6801: $($_.Exception.Message)"
}
try {
  $body = @{ jsonrpc = '2.0'; id = '1'; method = 'aria2.getVersion'; params = @("token:$secret") } | ConvertTo-Json
  $v = Invoke-RestMethod -Uri "http://127.0.0.1:$Port/jsonrpc" -Method Post -Body $body -ContentType 'application/json'
  Write-Host "aria2 $($v.result.version) is running on port $Port."
} catch {
  Write-Warning "aria2 did not answer on port $Port yet: $($_.Exception.Message)"
}
Set-Clipboard -Value $secret
Write-Host ''
Write-Host "RPC secret (copied to clipboard): $secret"
Write-Host 'Paste it into the extension: right-click the Ultimate Turbo Downloader icon > Options > RPC secret > Save.'
